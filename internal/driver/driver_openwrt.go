package driver

import (
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"strconv"
	"strings"
	"unicode/utf8"
)

// OpenWrt is a Linux distribution: its configuration is files, not a "show"
// command. The driver dumps /etc/config/* and everything /etc/sysupgrade.conf
// lists (the set sysupgrade itself preserves) over an exec channel.
//
// The device side is kept strictly read-only and minimal: ash builtins
// (echo, read, test, for, case, set) plus cat and ls, which every busybox build
// has. No od, find, head, sort or base64. Each file is introduced by a marker
// line carrying a random boundary generated by rusted for that run, so no file
// content can fake or break the framing; parsing, binary detection and base64
// all happen in openwrtPostProcess.

// openwrtMaxFile caps the size of one captured file; larger files are listed
// as skipped instead of being transferred.
const openwrtMaxFile = 1 << 20

// newBoundary returns a fresh random token for one capture.
func newBoundary() string { return "rusted-" + rand.Text() }

// openwrtRun returns d set up for one capture delimited by boundary.
func openwrtRun(d Driver, boundary string) Driver {
	d.Config = openwrtCommands(boundary)
	d.PostProcess = func(raw string) (string, error) {
		return openwrtPostProcess(raw, boundary, len(d.Config))
	}
	d.Prepare = nil
	return d
}

// openwrtCommands builds the two device-side commands. Both define f, which
// emits one path:
//
//	"\n<b> F <path>\n" + the exact file bytes   a regular file up to the cap
//	"\n<b> S <path>\n"                          a file over the cap (or ls failed)
//	"\n<b> L <path>\n"                          a symlink: recorded, never followed
//
// and recurses into real directories (hidden entries included). Symlinks are
// not followed, so a link cannot loop the walk or pull in a huge target, which
// matches what sysupgrade's own archive does. Each command ends with
// "\n<b> END\n" so a truncated capture is detected.
func openwrtCommands(b string) []string {
	f := `b=` + b + `; ` +
		`f(){ if [ -L "$1" ]; then echo; echo "$b L $1"; ` +
		`elif [ -d "$1" ]; then for e in "$1"/* "$1"/.[!.]* "$1"/..?*; do f "$e"; done; ` +
		`elif [ -f "$1" ]; then set -- "$1" $(ls -ld "$1" 2>/dev/null); ` +
		`if [ "$6" -le ` + strconv.Itoa(openwrtMaxFile) + ` ] 2>/dev/null; then echo; echo "$b F $1"; cat "$1"; ` +
		`else echo; echo "$b S $1"; fi; fi; }; `
	end := `echo; echo "$b END"`
	return []string{
		f + `for e in /etc/config/*; do f "$e"; done; ` + end,
		f + `if [ -f /etc/sysupgrade.conf ]; then f /etc/sysupgrade.conf; ` +
			`while read -r p || [ -n "$p" ]; do case "$p" in ''|'#'*) continue ;; esac; ` +
			`for e in ${p%/}; do f "$e"; done; done < /etc/sysupgrade.conf; fi; ` + end,
	}
}

// openwrtPostProcess turns the boundary-framed dump into the stored config: one
// "#### file: <path>" section per file, in capture order, first occurrence of
// a path wins. Text files are kept as-is; a file holding a NUL byte or invalid
// UTF-8 is binary and stored as wrapped base64 of the exact bytes received,
// keeping the backup text-only and diffable. The boundary itself never reaches
// the output, so it does not churn the diff.
func openwrtPostProcess(raw, boundary string, commands int) (string, error) {
	parts := strings.Split(raw, "\n"+boundary+" ")
	var b strings.Builder
	seen := map[string]bool{}
	ends := 0
	for _, p := range parts[1:] {
		head, body, _ := strings.Cut(p, "\n")
		if head == "END" {
			ends++
			continue
		}
		kind, path, ok := strings.Cut(head, " ")
		if !ok || seen[path] {
			continue
		}
		seen[path] = true
		b.WriteString("\n#### file: ")
		b.WriteString(path)
		switch kind {
		case "F":
			if strings.IndexByte(body, 0) >= 0 || !utf8.ValidString(body) {
				fmt.Fprintf(&b, " (binary, %d bytes, base64)\n", len(body))
				b.WriteString(wrapBase64(body))
				b.WriteString("\n")
				continue
			}
			b.WriteString("\n")
			b.WriteString(body)
			if body != "" && !strings.HasSuffix(body, "\n") {
				b.WriteString("\n")
			}
		case "S":
			fmt.Fprintf(&b, " (skipped: over %d bytes)\n", openwrtMaxFile)
		case "L":
			b.WriteString(" (symlink, not followed)\n")
		default:
			return "", fmt.Errorf("openwrt: unknown section %q", kind)
		}
	}
	if ends != commands {
		return "", fmt.Errorf("openwrt: incomplete capture (%d of %d commands finished)", ends, commands)
	}
	return b.String(), nil
}

// wrapBase64 encodes s as standard base64 wrapped at 76 columns, matching what
// coreutils' base64 emits.
func wrapBase64(s string) string {
	enc := base64.StdEncoding.EncodeToString([]byte(s))
	var b strings.Builder
	for len(enc) > 76 {
		b.WriteString(enc[:76])
		b.WriteString("\n")
		enc = enc[76:]
	}
	b.WriteString(enc)
	return b.String()
}
